import clsx from "clsx";
import Link from "next/link";
import type { ComponentProps, ReactNode } from "react";

export const cx = clsx;

type Variant = "primary" | "secondary" | "ghost" | "danger";
const variants: Record<Variant, string> = {
  primary: "bg-brand text-white hover:bg-indigo-800 shadow-sm disabled:bg-indigo-300",
  secondary: "bg-white text-ink border border-line hover:bg-slate-50 shadow-sm disabled:text-slate-400",
  ghost: "text-slate-600 hover:bg-slate-100 hover:text-ink disabled:text-slate-300",
  danger: "bg-white text-red-700 border border-red-200 hover:bg-red-50",
};

export function Button({ variant = "secondary", size = "md", className, ...props }: ComponentProps<"button"> & { variant?: Variant; size?: "sm" | "md" }) {
  return (
    <button
      className={cx(
        "inline-flex items-center justify-center gap-1.5 rounded-lg font-medium transition-colors disabled:cursor-not-allowed",
        size === "sm" ? "h-7 px-2.5 text-xs" : "h-9 px-3.5 text-sm",
        variants[variant],
        className,
      )}
      {...props}
    />
  );
}

export function ButtonLink({ variant = "secondary", className, ...props }: ComponentProps<typeof Link> & { variant?: Variant }) {
  return <Link className={cx("inline-flex h-9 items-center justify-center gap-1.5 rounded-lg px-3.5 text-sm font-medium transition-colors", variants[variant], className)} {...props} />;
}

export function Card({ className, children, ...props }: ComponentProps<"div">) {
  return (
    <div className={cx("rounded-xl border border-line bg-panel shadow-[0_1px_2px_rgba(15,23,42,0.04)]", className)} {...props}>
      {children}
    </div>
  );
}

const tones = {
  slate: "bg-slate-100 text-slate-700 ring-slate-200",
  indigo: "bg-indigo-50 text-indigo-700 ring-indigo-200",
  green: "bg-emerald-50 text-emerald-700 ring-emerald-200",
  amber: "bg-amber-50 text-amber-800 ring-amber-200",
  red: "bg-red-50 text-red-700 ring-red-200",
  sky: "bg-sky-50 text-sky-700 ring-sky-200",
  violet: "bg-violet-50 text-violet-700 ring-violet-200",
} as const;
export type Tone = keyof typeof tones;

export function Badge({ tone = "slate", className, children, title }: { tone?: Tone; className?: string; children: ReactNode; title?: string }) {
  return (
    <span title={title} className={cx("inline-flex items-center gap-1 whitespace-nowrap rounded-md px-1.5 py-0.5 text-[11px] font-medium ring-1 ring-inset", tones[tone], className)}>
      {children}
    </span>
  );
}

export const STATUS_META: Record<string, { tone: Tone; label: string; help: string }> = {
  verified: { tone: "green", label: "Verified", help: "Directly stated in a cited source" },
  supported: { tone: "sky", label: "Supported", help: "Reasonable interpretation of cited sources" },
  hypothesis: { tone: "amber", label: "Hypothesis", help: "Strategic judgement — not yet evidenced" },
  unknown: { tone: "slate", label: "Unknown", help: "Information is missing" },
};

export function PriorityBadge({ priority }: { priority: string }) {
  const tone: Tone = priority === "primary" ? "indigo" : priority === "secondary" ? "sky" : "slate";
  const label = priority === "primary" ? "Primary" : priority === "secondary" ? "Secondary" : "Deprioritized";
  return <Badge tone={tone}>{label}</Badge>;
}

export function ModeBadge({ mode }: { mode: string }) {
  if (mode === "live") return <Badge tone="green" title="Generated by the configured AI model from this project's evidence">AI generated</Badge>;
  if (mode === "mock") return <Badge tone="red" title="Development fixture — not real analysis">Dev mock</Badge>;
  if (mode === "demo") return <Badge tone="violet" title="Curated portfolio content, not generated live">Curated demo</Badge>;
  return <Badge>{mode}</Badge>;
}

export function SectionLabel({ children }: { children: ReactNode }) {
  return <div className="text-[11px] font-semibold uppercase tracking-wider text-muted">{children}</div>;
}

export function EmptyState({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="rounded-xl border border-dashed border-slate-300 bg-white/60 px-6 py-10 text-center">
      <div className="text-sm font-semibold">{title}</div>
      {children && <div className="mx-auto mt-1 max-w-md text-sm text-muted">{children}</div>}
      {action && <div className="mt-4">{action}</div>}
    </div>
  );
}

export function Notice({ tone = "amber", title, children, className }: { tone?: "amber" | "red" | "indigo" | "slate" | "green"; title?: string; children: ReactNode; className?: string }) {
  const map = {
    amber: "border-amber-200 bg-amber-50 text-amber-900",
    red: "border-red-200 bg-red-50 text-red-900",
    indigo: "border-indigo-200 bg-indigo-50 text-indigo-900",
    slate: "border-slate-200 bg-slate-50 text-slate-800",
    green: "border-emerald-200 bg-emerald-50 text-emerald-900",
  };
  return (
    <div className={cx("rounded-lg border px-3.5 py-2.5 text-sm", map[tone], className)}>
      {title && <div className="font-semibold">{title}</div>}
      <div className={title ? "mt-0.5" : ""}>{children}</div>
    </div>
  );
}

export function List({ items, className }: { items: string[]; className?: string }) {
  if (!items?.length) return <span className="text-sm text-muted">—</span>;
  return (
    <ul className={cx("list-disc space-y-1 pl-4 text-sm marker:text-slate-300", className)}>
      {items.map((i, idx) => (
        <li key={idx}>{i}</li>
      ))}
    </ul>
  );
}

export function Field({ label, children, className }: { label: string; children: ReactNode; className?: string }) {
  return (
    <div className={className}>
      <SectionLabel>{label}</SectionLabel>
      <div className="mt-1 text-sm leading-relaxed">{children}</div>
    </div>
  );
}

export const inputClass =
  "w-full rounded-lg border border-line bg-white px-3 py-2 text-sm shadow-sm outline-none placeholder:text-slate-400 focus:border-indigo-400 focus:ring-2 focus:ring-indigo-100";

export function usd(n: number) {
  if (n === 0) return "$0.00";
  if (n < 0.01) return "<$0.01";
  return `$${n.toFixed(2)}`;
}
